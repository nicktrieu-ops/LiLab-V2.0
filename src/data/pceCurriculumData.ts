export function resolveStudentPceLevel(
  age?: number,
  cefrLevel?: CefrLevel | string,
  cefrModifier?: '-' | 'standard' | '+'
): PceLevelCourse {
  // Match by CEFR & Age so every student gets an accurate default starting level in the 13-level pathway
  if (cefrLevel === 'C1 Advanced' || cefrLevel === 'C2 Proficiency') {
    return PCE_KIDS_CURRICULUM[12]; // Level 13: Future Leaders 5
  }
  if (cefrLevel === 'B2 First') {
    return cefrModifier === '+' ? PCE_KIDS_CURRICULUM[11] : PCE_KIDS_CURRICULUM[10]; // FL4 or FL3
  }
  if (cefrLevel === 'B1 Preliminary') {
    return PCE_KIDS_CURRICULUM[9]; // Level 10: Future Leaders 2
  }
  if (cefrLevel === 'A2 Key') {
    return age && age >= 11 ? PCE_KIDS_CURRICULUM[8] : PCE_KIDS_CURRICULUM[7]; // FL1 or YD5
  }
  if (cefrLevel === 'A2 Flyers') {
    return cefrModifier === '+' ? PCE_KIDS_CURRICULUM[7] : PCE_KIDS_CURRICULUM[6]; // YD5 or YD4
  }
  if (cefrLevel === 'A1 Movers') {
    return cefrModifier === '+' ? PCE_KIDS_CURRICULUM[5] : PCE_KIDS_CURRICULUM[4]; // YD3 or YD2
  }

  // Pre-A1 Starters or default based on age
  const safeAge = age ?? 6;
  if (safeAge <= 4) return PCE_KIDS_CURRICULUM[0]; // Little Explorers 1
  if (safeAge === 5) return PCE_KIDS_CURRICULUM[1]; // Little Explorers 2
  if (safeAge === 6 && cefrModifier === '-') return PCE_KIDS_CURRICULUM[2]; // Little Explorers 3
  return PCE_KIDS_CURRICULUM[3]; // Level 4: Young Discoverers 1 (Ages 6–7)
}
